/** Sort events chronologically. */
export function getSortedEvents() {
  return [...timelineEvents].sort((a, b) => a.year - b.year);
}

/** Group events by century for tickmark labeling. */
export function getCenturyMarks() {
  const years = timelineEvents.map((e) => e.year).sort((a, b) => a - b);
  const min = years[0];
  const max = years[years.length - 1];
  const marks = [];
  // Show a mark every ~500 years in ancient times, every century in modern
  for (let y = Math.ceil(min / 500) * 500; y <= max; y += y < 0 ? 500 : 100) {
    marks.push(y);
  }
  return marks;
}
